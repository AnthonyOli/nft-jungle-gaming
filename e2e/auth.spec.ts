import { ANA, DEMO, dev, expect, login, logout, open, test } from './fixtures'

const submit = (page: import('@playwright/test').Page) => page.getByRole('dialog').locator('form button[type=submit]')

test.describe('auth and session', () => {
  test('signup creates an account and logs in; it survives a reload; logout ends it', async ({ page }) => {
    await open(page, '/?login=true')
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Criar conta', exact: true }).first().click()
    await dialog.getByLabel('Nome de usuário').fill('novato')
    await dialog.getByLabel('E-mail').fill('novato@kurio.com')
    await dialog.getByLabel('Senha', { exact: true }).fill('123456')
    await dialog.getByLabel('Confirmar senha').fill('123456')
    await submit(page).click()
    await expect(dialog).toBeHidden()
    await open(page, '/perfil')
    await expect(page).toHaveURL(/\/perfil$/)
    await page.reload()
    await expect(page).toHaveURL(/\/perfil$/)
    await logout(page)
    await open(page, '/perfil')
    await expect(page).toHaveURL(/login=true/)
  })

  test('errors: wrong password, unknown e-mail, duplicate signup, mismatching confirmation', async ({ page }) => {
    await open(page, '/?login=true')
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('E-mail').fill(DEMO.email)
    await dialog.getByLabel('Senha', { exact: true }).fill('wrong-password')
    await submit(page).click()
    await expect(page.getByText('E-mail ou senha inválidos.')).toBeVisible()
    await dialog.getByLabel('E-mail').fill('ghost@kurio.com')
    await submit(page).click()
    await expect(page.getByText('E-mail ou senha inválidos.')).toBeVisible()

    await dialog.getByRole('button', { name: 'Criar conta', exact: true }).first().click()
    await dialog.getByLabel('Nome de usuário').fill('dup')
    await dialog.getByLabel('E-mail').fill(DEMO.email)
    await dialog.getByLabel('Senha', { exact: true }).fill('123456')
    await dialog.getByLabel('Confirmar senha').fill('654321')
    await submit(page).click()
    await expect(page.getByRole('alert').filter({ hasText: /senhas não coincidem|já está cadastrado/ })).toBeVisible()
    await dialog.getByLabel('Confirmar senha').fill('123456')
    await submit(page).click()
    await expect(page.getByText('Este e-mail já está cadastrado.')).toBeVisible()
  })

  test('private pages redirect to login and return afterwards (also cart → checkout)', async ({ page }) => {
    await open(page, '/pagamento')
    await expect(page).toHaveURL(/login=true.*redirect=%2Fpagamento|redirect=%2Fpagamento.*login=true/)
    await page.getByRole('dialog').getByLabel('E-mail').fill(DEMO.email)
    await page.getByRole('dialog').getByLabel('Senha', { exact: true }).fill(DEMO.password)
    await submit(page).click()
    await expect(page).toHaveURL(/\/pagamento$/)
  })

  test('a redirect to another origin is ignored', async ({ page }) => {
    await open(page, '/?login=true&redirect=//evil.example.com')
    await page.getByRole('dialog').getByLabel('E-mail').fill(DEMO.email)
    await page.getByRole('dialog').getByLabel('Senha', { exact: true }).fill(DEMO.password)
    await submit(page).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    expect(new URL(page.url()).hostname).not.toContain('evil')
  })

  test('switching users never shows the previous user\'s data', async ({ page }) => {
    await login(page, DEMO, '/perfil')
    await expect(page.getByLabel('Nome de exibição')).toHaveValue('Demo Collector')
    await logout(page)
    await login(page, ANA, '/perfil')
    await expect(page.getByLabel('Nome de exibição')).not.toHaveValue('Demo Collector')
    expect(await page.evaluate(() => document.body.innerText)).not.toContain('Demo Collector')
  })

  test('expired-session: a 401 mid-use reopens login, then returns to the page', async ({ page }) => {
    test.setTimeout(90_000)
    await open(page, '/', 'expired-session')
    await login(page, DEMO, '/perfil')
    await expect(page.getByLabel('Nome de exibição')).toBeVisible()
    await page.waitForTimeout(16_000)
    await page.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(page).toHaveURL(/login=true/)
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.getByRole('dialog').getByLabel('E-mail').fill(DEMO.email)
    await page.getByRole('dialog').getByLabel('Senha', { exact: true }).fill(DEMO.password)
    await submit(page).click()
    await expect(page).toHaveURL(/\/perfil$/)
  })

  test('expired-session at checkout: the form draft survives the re-login', async ({ page }) => {
    test.setTimeout(90_000)
    await open(page, '/', 'expired-session')
    await login(page, DEMO)
    await open(page, '/produto/0042')
    await page.getByRole('button', { name: /^Comprar( NFT)?$/ }).click()
    await page.getByRole('button', { name: 'Conectar e finalizar', exact: true }).click()
    await page.getByLabel('Observação do colecionador (opcional)').fill('entregar com cuidado')
    await page.getByRole('button', { name: 'Revisar compra', exact: true }).click()
    await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
    await expect(page.getByText('Carteira conectada')).toBeVisible()
    await page.waitForTimeout(16_000)
    await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.getByRole('dialog').getByLabel('E-mail').fill(DEMO.email)
    await page.getByRole('dialog').getByLabel('Senha', { exact: true }).fill(DEMO.password)
    await submit(page).click()
    await expect(page).toHaveURL(/\/pagamento$/)
    await expect(page.getByLabel('Observação do colecionador (opcional)')).toHaveValue('entregar com cuidado')
  })
})

test.describe('favorites', () => {
  const heart = (page: import('@playwright/test').Page) => page.getByRole('button', { name: /^Favorit/ })

  test('toggle is immediate and persists after a reload', async ({ page }) => {
    await login(page)
    await open(page, '/produto/0042')
    await expect(heart(page)).toHaveAttribute('aria-pressed', 'false')
    const saved = page.waitForResponse((r) => r.url().includes('/api/favorites/') && r.request().method() === 'PUT')
    await heart(page).click()
    await expect(heart(page)).toHaveAttribute('aria-pressed', 'true')
    await saved
    await page.reload()
    await expect(heart(page)).toHaveAttribute('aria-pressed', 'true')
    await heart(page).click()
    await expect(heart(page)).toHaveAttribute('aria-pressed', 'false')
  })

  test('favorites are per user', async ({ page }) => {
    await login(page, DEMO)
    await open(page, '/produto/0042')
    await heart(page).click()
    await expect(heart(page)).toHaveAttribute('aria-pressed', 'true')
    await logout(page)
    await login(page, ANA)
    await open(page, '/produto/0042')
    await expect(heart(page)).toHaveAttribute('aria-pressed', 'false')
  })

  test('a failing request rolls the heart back and says so', async ({ page }) => {
    await login(page)
    await open(page, '/produto/0042')
    await dev(page, 'POST', '/api/dev/fail', { path: '/api/favorites', times: 1, status: 500 })
    await heart(page).click()
    await expect(page.getByText('Não foi possível atualizar seus favoritos.')).toBeVisible()
    await expect(heart(page)).toHaveAttribute('aria-pressed', 'false')
  })

  test('a guest who favorites is asked to log in', async ({ page }) => {
    await open(page, '/produto/0042')
    await heart(page).click()
    await expect(page).toHaveURL(/login=true/)
    await page.keyboard.press('Escape')
    await expect(heart(page)).toHaveAttribute('aria-pressed', 'false')
  })
})
