import { ANA, DEMO, expect, login, logout, open, test } from './fixtures'

const PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==', 'base64')
const save = (page: import('@playwright/test').Page) => page.getByRole('button', { name: 'Salvar', exact: true })

test.describe('profile', () => {
  test('is private: a guest is sent to login and comes back to the profile', async ({ page }) => {
    await open(page, '/perfil')
    await expect(page).toHaveURL(/login=true/)
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('E-mail').fill(DEMO.email)
    await dialog.getByLabel('Senha', { exact: true }).fill(DEMO.password)
    await dialog.locator('form button[type=submit]').click()
    await expect(page).toHaveURL(/\/perfil$/)
    await expect(page.getByLabel('Nome de exibição')).toHaveValue('Demo Collector')
  })

  test('edited data persists after a reload; each user only sees their own', async ({ page }) => {
    await login(page, DEMO, '/perfil')
    await page.getByLabel('Nome de exibição').fill('Colecionador Novo')
    await save(page).click()
    await expect(page.getByText('Alterações salvas.')).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Nome de exibição')).toHaveValue('Colecionador Novo')
    await logout(page)
    await login(page, ANA, '/perfil')
    await expect(page.getByLabel('Nome de exibição')).not.toHaveValue('Colecionador Novo')
  })

  test('client validation messages, and the server rejects a taken e-mail on the right field', async ({ page }) => {
    await login(page, DEMO, '/perfil')
    await page.getByLabel('Nome de exibição').fill('')
    await page.getByRole('main').getByRole('textbox', { name: /^E-mail/ }).fill('nope')
    await save(page).click()
    await expect(page.getByText('Campo obrigatório.')).toBeVisible()
    await expect(page.getByText('Informe um e-mail válido.')).toBeVisible()
    await page.getByLabel('Nome de exibição').fill('Demo')
    await page.getByRole('main').getByRole('textbox', { name: /^E-mail/ }).fill(ANA.email)
    await save(page).click()
    await expect(page.getByText('Este e-mail já está em uso.')).toBeVisible()
  })

  test('password change: wrong current password is refused, a mismatch is caught, the new one works at login', async ({ page }) => {
    await login(page, DEMO, '/perfil')
    await page.getByLabel('Senha atual').fill('wrong-one')
    await page.getByLabel('Nova senha', { exact: true }).fill('abcdef')
    await page.getByLabel('Confirmar nova senha').fill('abcdef')
    await save(page).click()
    await expect(page.getByText('A senha atual está incorreta.')).toBeVisible()

    await page.getByLabel('Senha atual').fill(DEMO.password)
    await page.getByLabel('Confirmar nova senha').fill('different')
    await save(page).click()
    await expect(page.getByText('As senhas não coincidem.')).toBeVisible()

    await page.getByLabel('Confirmar nova senha').fill('abcdef')
    await save(page).click()
    await expect(page.getByText('Alterações salvas.')).toBeVisible()

    await logout(page)
    await open(page, '/?login=true')
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('E-mail').fill(DEMO.email)
    await dialog.getByLabel('Senha', { exact: true }).fill(DEMO.password)
    await dialog.locator('form button[type=submit]').click()
    await expect(page.getByText('E-mail ou senha inválidos.')).toBeVisible()
    await dialog.getByLabel('Senha', { exact: true }).fill('abcdef')
    await dialog.locator('form button[type=submit]').click()
    await expect(dialog).toBeHidden()
  })

  test('avatar: upload, persists after reload, can be removed; a non-image is refused', async ({ page }) => {
    await login(page, DEMO, '/perfil')
    const file = page.getByLabel('Alterar', { exact: true })
    await file.setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('hello') })
    await expect(page.getByText('Use uma imagem PNG, JPEG ou WebP.')).toBeVisible()
    await file.setInputFiles({ name: 'me.png', mimeType: 'image/png', buffer: PNG })
    await expect(page.getByRole('img', { name: 'Foto do perfil' })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('img', { name: 'Foto do perfil' })).toBeVisible()
    await page.getByRole('button', { name: 'Remover', exact: true }).click()
    await expect(page.getByRole('img', { name: 'Foto do perfil' })).toBeHidden()
  })
})

test.describe('wallets', () => {
  const nickname = (page: import('@playwright/test').Page) => page.getByLabel('Apelido da carteira secundária')

  test('secondary wallet: add, validate, edit, remove, persisted across reloads, offered at checkout', async ({ page }) => {
    await login(page, ANA, '/perfil/carteiras')
    await page.getByRole('button', { name: 'Adicionar carteira secundária', exact: true }).click()
    await nickname(page).fill('Cofre')
    await page.getByRole('combobox', { name: /^Rede/ }).last().click()
    await page.getByRole('option', { name: 'Polygon' }).click()
    await page.getByRole('combobox', { name: /^Tipo de carteira/ }).last().click()
    await page.getByRole('option', { name: 'MetaMask' }).click()
    await page.getByLabel('Endereço da carteira').last().fill('zzz')
    await page.getByRole('button', { name: 'Salvar carteira', exact: true }).last().click()
    await expect(page.getByText(/Endereço inválido/)).toBeVisible()
    await page.getByLabel('Endereço da carteira').last().fill('0xabcdef1234567890')
    await page.getByRole('button', { name: 'Salvar carteira', exact: true }).last().click()
    await expect(page.getByText('Cofre')).toBeVisible()
    await page.reload()
    await expect(page.getByText('Cofre')).toBeVisible()

    await open(page, '/produto/0042')
    await page.getByRole('button', { name: /^Comprar( NFT)?$/ }).click()
    await page.getByRole('button', { name: 'Conectar e finalizar', exact: true }).click()
    await expect(page.getByRole('radio', { name: /Secundária/ })).toBeVisible()

    await open(page, '/perfil/carteiras')
    await page.getByRole('button', { name: 'Editar carteira secundária', exact: true }).click()
    await nickname(page).fill('Cofre 2')
    await page.getByRole('button', { name: 'Salvar carteira', exact: true }).last().click()
    await expect(page.getByText('Cofre 2')).toBeVisible()
    await page.getByRole('button', { name: 'Remover carteira', exact: true }).click()
    await expect(page.getByText('Você ainda não adicionou uma carteira secundária.')).toBeVisible()
    await page.reload()
    await expect(page.getByText('Você ainda não adicionou uma carteira secundária.')).toBeVisible()
  })

  test('main wallet address is validated and the change is saved', async ({ page }) => {
    await login(page, DEMO, '/perfil/carteiras')
    const address = page.getByLabel('Endereço da carteira').first()
    await address.fill('not-hex')
    await page.getByRole('button', { name: 'Salvar carteira', exact: true }).first().click()
    await expect(page.getByText(/Endereço inválido/)).toBeVisible()
    await address.fill('0xaaaaaaaaaaaaaaaa')
    await page.getByRole('button', { name: 'Salvar carteira', exact: true }).first().click()
    await expect(page.getByText('Carteira salva.')).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Endereço da carteira').first()).toHaveValue('0xaaaaaaaaaaaaaaaa')
  })
})
